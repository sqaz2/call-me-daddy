const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base=process.env.BASE_URL||'http://127.0.0.1:8765';
  await page.addInitScript(()=>{window.__shares=[];Object.defineProperty(navigator,'share',{value:data=>{window.__shares.push(data);return Promise.resolve()}})});
  await page.goto(base+'/music/',{waitUntil:'load'});
  assert.equal(new URL(page.url()).pathname,'/');
  assert.ok(await page.getByRole('searchbox',{name:'Search songs',exact:true}).isVisible());
  await page.getByRole('link',{name:'All releases →',exact:true}).waitFor();
  assert.deepEqual(await page.locator('.navlinks a').allTextContents(),['Search songs','WinHamp','My Music','Latest','Reading','Archive','About']);
  assert.equal(await page.locator('.navlinks a').filter({hasText:'My Music'}).getAttribute('href'),'/my-music/');
  await page.locator('.navlinks a[href="/reading/"]').click();
  await page.locator('.reading-card').click();
  await page.locator('#article-title').waitFor();
  assert.equal(new URL(page.url()).pathname,'/reading/ai-audio-detectors/');
  for(const width of [320,390,1440]){
    await page.setViewportSize({width,height:844});
    for(const size of ['normal','large']){
      await page.locator(`[data-text-size="${size}"]`).click();
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`Reading page fits ${width}px at ${size} text size`);
    }
  }
  await page.reload({waitUntil:'load'});
  assert.equal(await page.locator('[data-text-size="large"]').getAttribute('aria-pressed'),'true');
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-share-article]').click();
  assert.equal(await page.evaluate(()=>window.__shares.at(-1).url),'https://callmedaddy.musicsubject.com/reading/ai-audio-detectors/');
  await page.locator('.reading-contents summary').click();
  await page.locator('.reading-contents a[href="#clues"]').click();
  assert.equal(new URL(page.url()).hash,'#clues');
  assert.equal(await page.evaluate(()=>[...document.querySelectorAll('audio')].some(m=>!m.paused)),false,'Reading loads silently');
  await page.goto(base+'/updates/',{waitUntil:'load'});
  assert.ok((await page.locator('.update-card').first().boundingBox()).y<700,'The first release is on the initial mobile screen');
  assert.equal(await page.locator('.updates-summary').count(),0);
  const search=page.getByRole('searchbox',{name:'Search releases'});
  await search.fill('Cheap to Inform');assert.equal(await page.locator('.update-card').count(),1);
  await page.getByRole('button',{name:/Share Cheap to Inform/}).click();
  assert.ok((await page.evaluate(()=>window.__shares.at(-1).text)).match(/https?:\/\//));
  await search.fill('');await page.getByRole('button',{name:'Site notes',exact:true}).click();
  assert.ok((await page.locator('#updatesResultCount').innerText()).includes('site notes'));
  assert.equal(await page.locator('#understanding-ai-audio .update-open').getAttribute('href'),'/reading/ai-audio-detectors/','The article announcement opens the full article');
  await search.fill('The radio listens');
  assert.ok((await page.locator('.update-open').first().getAttribute('href')).startsWith('/updates/'),'A standard site note still opens the note itself');
  await search.fill('');
  await page.getByRole('button',{name:'Music',exact:true}).click();
  fs.mkdirSync('/tmp/replay-qa',{recursive:true});
  await page.screenshot({path:'/tmp/replay-qa/latest-simple-mobile.png'});
  await page.goto(base+'/music/?song=survival-mode&version=celtic-north-remix',{waitUntil:'load'});
  assert.ok((await page.locator('#listenTitle').innerText()).includes('Survival Mode'));
  assert.ok((await page.locator('#listenDetail').innerText()).includes('Earlier Celtic North Remix'));
  assert.equal(await page.locator('.music-section').isVisible(),false);
  assert.equal(await page.locator('#cmdRadioGate').count(),0);
  assert.equal(await page.locator('#catalogPlayer').isVisible(),false,'Old player controls must stay hidden before the first play');
  assert.equal(await page.locator('#listenContext').textContent(),'Selected recording');
  assert.equal(await page.evaluate(()=>[...document.querySelectorAll('audio')].some(m=>!m.paused)),false);
  await page.locator('#listenPlay').click();
  await page.waitForFunction(()=>window.CMDUniversalPlayer.getMedia()?.currentTime>0.1);
  assert.equal(await page.evaluate(()=>window.CMDUniversalPlayer.getTrack().variantId),'celtic-north-remix');
  assert.equal(await page.locator('.cmd-universal-player:visible').count(),1);
  assert.equal(await page.locator('#catalogPlayer').isVisible(),false);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'/tmp/replay-qa/selected-version-mobile.png'});
  await page.evaluate(()=>{window.__navigationOwner=window.CMDUniversalPlayer.getMedia()});
  await page.getByRole('link',{name:'Search songs',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('iframe')].some(f=>f.contentDocument?.getElementById('homeSongSearch')));
  assert.equal(await page.evaluate(()=>window.__navigationOwner===window.CMDUniversalPlayer.getMedia()&&!window.__navigationOwner.paused),true);
  const homeFrame=page.frames().find(frame=>frame!==page.mainFrame()&&new URL(frame.url()).pathname==='/');
  assert.ok(homeFrame,'The homepage is the current reading entry point');
  await homeFrame.locator('.navlinks a[href="/reading/"]').click();
  await page.waitForFunction(()=>[...document.querySelectorAll('iframe')].some(f=>f.contentDocument?.getElementById('reading-list')));
  const readingFrame=page.frames().find(frame=>frame!==page.mainFrame()&&new URL(frame.url()).pathname==='/reading/');
  await readingFrame.locator('.reading-card').click();
  await page.waitForFunction(()=>[...document.querySelectorAll('iframe')].some(f=>f.contentDocument?.getElementById('article-title')));
  assert.equal(await page.evaluate(()=>window.__navigationOwner===window.CMDUniversalPlayer.getMedia()&&!window.__navigationOwner.paused),true,'Opening the article keeps the same recording playing');
  assert.equal(await page.locator('.cmd-universal-player:visible').count(),1);
  await page.screenshot({path:'/tmp/replay-qa/reading-while-playing-mobile.png'});
  await context.close();
  const rawContext=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const raw=await rawContext.newPage();raw.on('pageerror',e=>errors.push(e.message));
  await raw.goto(base+'/music/?song=numbness-as-a-trap&version=barbershop-wobble-edit',{waitUntil:'load'});
  await raw.locator('#listenPlay').click();
  await raw.waitForFunction(()=>window.CMDUniversalPlayer.getMedia()?.currentTime>0.1);
  assert.equal(await raw.evaluate(()=>window.CMDUniversalPlayer.getTrack().variantId),'barbershop-wobble-edit');
  assert.ok((await raw.evaluate(()=>window.CMDUniversalPlayer.getMedia().src)).endsWith('/barbershop-wobble.mp3'));
  await rawContext.close();
  const radioContext=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const radio=await radioContext.newPage();radio.on('pageerror',e=>errors.push(e.message));
  await radio.goto(base+'/music/?intent=surprise',{waitUntil:'load'});
  await radio.getByRole('button',{name:'Play this mix'}).click();
  await radio.waitForFunction(()=>window.CMDUniversalPlayer.getMedia()?.currentTime>0.1);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({homeOwnsSearch:true,readingLayouts:true,articleSharing:true,readingWhilePlaying:true,latestOnFirstScreen:true,releaseSearch:true,siteNotes:true,exactVersion:true,explicitHeavyVersion:true,singleDock:true,browseWhilePlaying:true,radioFirstTap:true,errors}));
  await radioContext.close();
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
